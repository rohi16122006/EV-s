/**
 * Calculates scientifically grounded LCA stage emissions based on the empirical dataset row
 */
export function calculateCropModel(cropItem) {
  const yieldKg = cropItem.yield_kg_ha || 1000;
  
  // 1. Synthetic Nitrogen Fertilization (N2O flux + synthesis energy)
  // Direct emission: 1% N emitted as N2O-N => 4.29 kg CO2e / kg N + 3.0 kg CO2e synthesis
  const nitrogenTotalCO2e = cropItem.n_kg_ha * 7.29;
  const nitrogenPerKg = Number((nitrogenTotalCO2e / yieldKg).toFixed(3));

  // 2. On-Farm Diesel Fuel
  // 2.68 kg CO2e per liter diesel
  const dieselTotalCO2e = cropItem.diesel_l_ha * 2.68;
  const dieselPerKg = Number((dieselTotalCO2e / yieldKg).toFixed(3));

  // 3. Pesticides / Crop Protection
  // ~11.0 kg CO2e per kg active ingredient
  const pestTotalCO2e = cropItem.pest_kg_ai_ha * 11.0;
  const pestPerKg = Number((pestTotalCO2e / yieldKg).toFixed(3));

  // 4. Groundwater Irrigation Pumping (CEA Grid factor 716 g/kWh)
  // Consumptive water pumping = irrigated_share * growth_days * kc * 0.12 kg CO2e
  const irrigationTotalCO2e = cropItem.irrigated_share * cropItem.growth_days * cropItem.kc * 2.8;
  const irrigationPerKg = Number((irrigationTotalCO2e / (yieldKg / 1000)).toFixed(3));

  // 5. Methane Flux (Flooded Paddy)
  // 28x GWP over 100-year horizon
  const methaneTotalCO2e = cropItem.ch4_kg_ha_day * cropItem.growth_days * 28.0;
  const methanePerKg = Number((methaneTotalCO2e / yieldKg).toFixed(3));

  // Total Cultivation Stage
  const cultivation = Number((nitrogenPerKg + dieselPerKg + pestPerKg + irrigationPerKg + methanePerKg).toFixed(3));

  // Processing Stage (based on category)
  let processing = 0.05;
  if (cropItem.category === "Fruit") processing = 0.06;
  if (cropItem.category === "Cereal") processing = 0.08;
  if (cropItem.category === "Plantation") processing = 0.15;

  // Packaging (typical Indian standard)
  let packaging = 0.08;
  if (cropItem.category === "Fruit") packaging = 0.11; // Corrugated box
  if (cropItem.category === "Cereal" || cropItem.category === "Pulse") packaging = 0.03; // Jute sack

  // Transport (Average 1,000 km freight)
  const transport = Number(((1000 * (cropItem.needs_cold_storage ? 118 : 95)) / 1000000).toFixed(3));

  // Retail & Spoilage
  // Baseline storage days: 4 days for perishables, 1 day for staples
  const transitStorageDays = cropItem.needs_cold_storage ? 5 : 2;
  const spoilageLossKg = (cropItem.handling_loss_pct + (cropItem.spoil_rate_pct_day_13c * transitStorageDays)) / 100;
  const retailAndWaste = Number(((cultivation + transport) * spoilageLossKg).toFixed(3));

  const totalPerKg = Number((cultivation + processing + packaging + transport + retailAndWaste).toFixed(3));

  return {
    breakdown: {
      nitrogenPerKg,
      dieselPerKg,
      pestPerKg,
      irrigationPerKg,
      methanePerKg,
      cultivation,
      processing,
      packaging,
      transport,
      retailAndWaste,
      totalPerKg,
    },
    coldChain: {
      needsColdStorage: cropItem.needs_cold_storage === 1,
      targetReeferTempC: cropItem.reefer_temp_c,
      spoilageRiskPerDayPct: cropItem.spoil_rate_pct_day_13c,
      handlingLossPct: cropItem.handling_loss_pct,
    }
  };
}
